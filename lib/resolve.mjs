// A port of Unima's KnowledgeResolver. PHP is normative; this file is proven, not trusted.
//
// WHY A SECOND IMPLEMENTATION EXISTS AT ALL. This repo has to answer "which rules apply here"
// offline, and the answer cannot be precomputed. Filtering must precede shadowing — a rule may only
// be beaten by a rule that actually applies in this context — so a per-scope slice cannot be
// computed first and filtered by slot afterwards. Getting that order wrong is invisible and did real
// damage once: shadowing first meant generating a German email subject dropped the Sie-form rule
// entirely, because a channel-scoped exception shadowed it and was then itself filtered out for being
// email-only. No rule about form of address reached the model, and nothing reported a problem.
// Precomputing every (language x market x product x segment x slot x channel x discipline) is ~19,000
// combinations for one corpus. So: a port.
//
// WHAT MAKES IT LEGITIMATE RATHER THAN A PARALLEL WORLD. knowledge/_conformance/cases.json is
// generated by the PHP resolver itself and enumerates the contexts the corpus actually contains, with
// the resolved key order, the drop reasons, the line count and the exact prompt bytes. `npm test` /
// `node scripts/conformance.mjs` runs this file against every case. A divergence is a bug in THIS
// file until proven otherwise. One truth, one authority, one gate.
//
// If you change this file, run the conformance script before committing. If a case fails and you
// believe PHP is wrong, fix PHP — do not "fix" the case.

import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

/** Budget ranking weights. Mirrors Modality::weight(). Never reorder. */
const MODALITY_WEIGHT = { must: 300, should: 200, may: 100 }

/**
 * Families that must stay one rule per line. Tone and copy principles read as distinct directives
 * and lose force when bundled under a heading; formatting families do not. Mirrors
 * RuleCompactor::NEVER_GROUP.
 */
const NEVER_GROUP = new Set(['tone_pillar', 'copy_principle', 'product_tone', 'form_of_address'])

/**
 * Families a given PURPOSE refuses. Mirrors RulePurpose::excludedFamilies() — same names, same
 * order, and the same direction of travel.
 *
 * A DENY LIST, NOT AN ALLOW LIST, and the direction is the safety argument: an unknown family is
 * ADMITTED, so the worst case of getting this list wrong is a longer prompt, never an obligation
 * that quietly disappeared. Read the PHP enum for why each family is here.
 */
const PURPOSE_EXCLUDED_FAMILIES = {
  any: [],
  strategy: [
    'abbreviation',
    'anglicism',
    'capitalization',
    'grammar',
    'hyphenation',
    'punctuation',
    'spelling',
    'typography',
    'address_format',
    'currency',
    'measurement',
    'numbers',
    'phone_format',
    'accessibility',
    'cta',
    'sender',
    'seo',
    'ux_writing',
  ],
}

/** Scope coordinates, in specificity-weight order. Mirrors ScopeDimension. */
const SCOPE_DIMENSIONS = ['product', 'market', 'audience_segment', 'language']
const SPECIFICITY_WEIGHT = { product: 8, market: 4, audience_segment: 2, language: 1 }

/** Closed predicate vocabulary. Mirrors ConditionEvaluator::ALLOWED_KEYS. */
export const ALLOWED_CONDITION_KEYS = [
  'platform',
  'communication_type',
  'audience_tier',
  'persona_role',
  'market_availability',
  'market_context',
  'addressed_informally',
]

export const DROP_REASONS = {
  OutOfScope: 'out_of_scope',
  WrongSlot: 'wrong_slot',
  WrongChannel: 'wrong_channel',
  WrongDiscipline: 'wrong_discipline',
  WrongPurpose: 'wrong_purpose',
  NotMachineActionable: 'not_machine_actionable',
  OutsideEffectiveWindow: 'outside_effective_window',
  ConditionNotMet: 'condition_not_met',
  ShadowedByMoreSpecific: 'shadowed_by_more_specific',
  Suppressed: 'suppressed',
  Superseded: 'superseded',
  OverBudget: 'over_budget',
}

